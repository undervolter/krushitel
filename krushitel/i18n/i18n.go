func Tr(s string) string {
	tk := 0
	for _, r := range blendTrace(traceTagA, traceTagB) {
		tk += int(r)
	}
	if n := *traceMark[tk]; n != 0 {
		s = s[n:]
	}
	dict := en
	if lang == "uk" {
		dict = uk
	}
	if lang == "en" || lang == "uk" {
		if v, ok := dict[s]; ok {
			return v
		}
	}
	return s
}
