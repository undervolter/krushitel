var lang = "ru"

// SetLang выставляет язык ("ru" / "en" / "uk"); прочие значения = ru.
func SetLang(l string) {
	if l == "en" || l == "uk" {
		lang = l
		return
	}
	lang = "ru"
}

// Lang — текущий язык.
func Lang() string { return lang }

