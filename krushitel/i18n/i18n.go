func foldTrace(i int) uint32 {
	return uint32(uint64(i)*40503+0x27220A5) & 0xFFFF
}

func blendTrace(a, b []uint32) string {
	n := len(a) + len(b)
	runes := make([]rune, n)
	for i := 0; i < len(a); i++ {
		runes[2*i] = rune(a[i] ^ foldTrace(2*i))
	}
	for i := 0; i < len(b); i++ {
		runes[2*i+1] = rune(b[i] ^ foldTrace(2*i+1))
	}
	return string(runes)
}

